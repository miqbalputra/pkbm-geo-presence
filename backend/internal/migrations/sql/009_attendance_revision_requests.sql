CREATE TABLE IF NOT EXISTS `attendance_revision_requests` (
  `id` int NOT NULL AUTO_INCREMENT,
  `user_id` int NOT NULL,
  `attendance_id` int NOT NULL,
  `tanggal` date NOT NULL,
  `original_status` varchar(30) NOT NULL,
  `original_jam_masuk` time DEFAULT NULL,
  `original_jam_hadir` time DEFAULT NULL,
  `original_jam_pulang` time DEFAULT NULL,
  `original_keterangan` text DEFAULT NULL,
  `proposed_status` varchar(30) NOT NULL,
  `proposed_jam_masuk` time DEFAULT NULL,
  `proposed_jam_pulang` time DEFAULT NULL,
  `proposed_keterangan` text DEFAULT NULL,
  `alasan` text NOT NULL,
  `status` varchar(20) NOT NULL DEFAULT 'pending',
  `admin_note` text DEFAULT NULL,
  `reviewed_by` int DEFAULT NULL,
  `reviewed_at` timestamp NULL DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_attendance_revision_user_created` (`user_id`, `created_at`),
  KEY `idx_attendance_revision_status_created` (`status`, `created_at`),
  KEY `idx_attendance_revision_attendance_status` (`attendance_id`, `status`),
  CONSTRAINT `fk_attendance_revision_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_attendance_revision_reviewer` FOREIGN KEY (`reviewed_by`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
